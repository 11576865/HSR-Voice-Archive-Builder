"""Keep the last published archive usable when a rebuild fails."""

from __future__ import annotations

import os
import shutil
import tempfile
from contextlib import contextmanager
from contextvars import ContextVar
from pathlib import Path
from typing import Iterator


BUILD_MARKER = ".build_in_progress"

# A build can validate its own just-published MKV without treating its
# marker as a foreign write. ContextVar values are copied into child asyncio
# tasks and copy_context snapshots; an immutable path tuple alone would keep
# granting authority AFTER the publishing context manager exits. Every copy
# shares a mutable revocable lease, so stale contexts cannot waive another
# build's marker after the original transaction ends.
class _BuildLease:
    __slots__ = ("output", "active")

    def __init__(self, output: Path) -> None:
        self.output = output.resolve()
        self.active = True


_OWNED_BUILD_OUTPUTS: ContextVar[tuple[_BuildLease, ...]] = ContextVar(
    "hsr_owned_publication_outputs", default=()
)


def owns_published_build(output: Path) -> bool:
    """True only while a matching protected build lease is still active."""
    resolved = output.resolve()
    return any(lease.active and lease.output == resolved
               for lease in _OWNED_BUILD_OUTPUTS.get())


# These are generated by the build itself. Human edits, downloaded sources and
# translation checkpoints deliberately remain outside the rollback set.
ARCHIVE_FILES = (
    "manifest.json",
    "archive_bundle_receipt.json",
    "subtitle_export_receipt.json",
    "manifest.csv",
    "bilingual_index_corrected.csv",
    "timeline_resolved.json",
    "HSR_Voice_Archive.srt",
    "HSR_Voice_Archive.ass",
    "HSR_Voice_Archive_Black.mkv",
        "HSR_Voice_Archive_Bundle.mkv",
    "ass_layout_overflow_report.json",
    "build_report.json",
    "continuous.flac",
)
ARCHIVE_DIRS = (
    "chapter_flac",
)
PUBLISHED_STAGES = (
    "stages/05_manifest.json",
    "stages/06_audio_state.json",
    "stages/final_report.json",
)


@contextmanager
def preserve_published_archive(output: Path, state: Path) -> Iterator[None]:
    """Restore the old coherent artifact set on an ordinary build failure.

    The large audio/video outputs are replaced or removed by the builder, so
    hard links can preserve them without copying gigabytes. Text artifacts
    are copied because some CSV writers overwrite their existing inode.
    """
    output.mkdir(parents=True, exist_ok=True)
    marker = output / BUILD_MARKER
    previously_interrupted = marker.exists()
    paths = [output / name for name in ARCHIVE_FILES]
    paths.extend(state / name for name in PUBLISHED_STAGES)
    directory_paths = [output / name for name in ARCHIVE_DIRS]
    with tempfile.TemporaryDirectory(prefix=".hsr-published-", dir=output.parent) as td:
        backup = Path(td)
        originals: dict[Path, Path | None] = {}
        for index, path in enumerate(paths):
            saved = backup / f"file-{index}"
            if path.is_file():
                if path.name in {"continuous.flac", "HSR_Voice_Archive_Black.mkv", "HSR_Voice_Archive_Bundle.mkv"}:
                    try:
                        os.link(path, saved)
                    except (OSError, AttributeError):
                        shutil.copy2(path, saved)
                else:
                    shutil.copy2(path, saved)
                originals[path] = saved
            else:
                originals[path] = None

        directory_originals: dict[Path, Path | None] = {}
        for index, path in enumerate(directory_paths):
            saved = backup / f"dir-{index}"
            if path.is_dir():
                def _link_or_copy(src: str, dst: str) -> str:
                    try:
                        os.link(src, dst)
                    except (OSError, AttributeError):
                        shutil.copy2(src, dst)
                    return dst
                shutil.copytree(path, saved, copy_function=_link_or_copy)
                directory_originals[path] = saved
            else:
                directory_originals[path] = None
        marker.touch(exist_ok=True)
        lease = _BuildLease(output)
        token = _OWNED_BUILD_OUTPUTS.set(
            (*_OWNED_BUILD_OUTPUTS.get(), lease)
        )
        try:
            yield
            # Committing the publication includes removing the busy marker.
            # If this final mutation fails, roll back the entire previous
            # coherent artifact set instead of stranding a newly published
            # archive behind an apparently interrupted build.
            marker.unlink(missing_ok=True)
        except BaseException:
            try:
                for path, saved in originals.items():
                    if saved is None:
                        path.unlink(missing_ok=True)
                    else:
                        path.parent.mkdir(parents=True, exist_ok=True)
                        os.replace(saved, path)
                for path, saved in directory_originals.items():
                    if path.exists():
                        shutil.rmtree(path)
                    if saved is not None:
                        path.parent.mkdir(parents=True, exist_ok=True)
                        os.replace(saved, path)
            except BaseException:
                # Keep the marker: the user must not see a mixed output as a
                # successfully completed archive if restoration also fails.
                raise
            if not previously_interrupted:
                marker.unlink(missing_ok=True)
            raise
        finally:
            # Revoke even if rollback/commit failed. A context copied by an
            # asynchronous child before this exit must never authenticate a
            # later, independent transaction touching the same output.
            lease.active = False
            _OWNED_BUILD_OUTPUTS.reset(token)
